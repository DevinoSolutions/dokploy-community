import { readFileSync } from "node:fs";
import { getBuildComposeCommand } from "@dokploy/server/utils/builders/compose";
import { describe, expect, it, vi } from "vitest";
import {
	GOLDEN_BASE_COMPOSE,
	GOLDEN_CASES,
	GOLDEN_REMOTE_BUILD,
} from "./golden-build-command-cases";

// The builder joins paths with node:path; pin it to posix so the fixture does
// not depend on the OS the test runs on.
vi.mock("node:path", async () => {
	const actual = await vi.importActual<typeof import("node:path")>("node:path");
	return { ...actual, ...actual.posix, default: actual.posix };
});
vi.mock("@dokploy/server/utils/docker/domain", () => ({
	writeDomainsToCompose: vi.fn().mockResolvedValue(""),
}));

/**
 * `__fixtures__/build-command-golden.json` was generated by the builder as it
 * was on canary before the deploy guardrails (90c431804). A compose that did
 * not opt in must keep getting exactly these scripts.
 */
const golden: Record<string, string> = JSON.parse(
	readFileSync(
		new URL("./__fixtures__/build-command-golden.json", import.meta.url),
		"utf8",
	),
);

const render = (
	name: string,
	deployGuardrails: unknown,
	withProperty = true,
) => {
	const c = GOLDEN_CASES[name];
	if (!c) throw new Error(`Unknown golden case ${name}`);
	return getBuildComposeCommand(
		{
			...GOLDEN_BASE_COMPOSE,
			...c.overrides,
			...(withProperty ? { deployGuardrails } : {}),
		} as never,
		{
			deploymentId: "dep-1",
			freshVolumes: c.options.freshVolumes,
			remoteBuild: c.options.remoteBuild ? GOLDEN_REMOTE_BUILD : undefined,
		},
	);
};

describe("golden build command (guardrails off)", () => {
	it("covers every case of the fixture", () => {
		expect(Object.keys(golden).sort()).toEqual(
			Object.keys(GOLDEN_CASES).sort(),
		);
	});

	const offValues: Array<[string, unknown, boolean]> = [
		["no deployGuardrails property", undefined, false],
		["deployGuardrails null", null, true],
		["deployGuardrails undefined", undefined, true],
		[
			"every flag false",
			{ phaseTimestamps: false, dockerEvents: false, healthCheck: null },
			true,
		],
		["an empty object", {}, true],
	];

	for (const name of Object.keys(GOLDEN_CASES)) {
		it.each(offValues)(
			`${name}: %s equals the pre-guardrails script`,
			async (_label, value, withProperty) => {
				expect(await render(name, value, withProperty)).toBe(golden[name]);
			},
		);
	}

	it("a guardrail that is on does change the script", async () => {
		expect(await render("compose", { phaseTimestamps: true })).not.toBe(
			golden.compose,
		);
	});
});
